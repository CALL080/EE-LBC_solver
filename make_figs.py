"""Generate the data parts of Fig. 2 and Table 3 from the logs (shared by the English paper and the Japanese draft).

Run:  python code/make_figs.py
Writes outputs/figs/fig_weights.tex (Fig. 2) and outputs/figs/tab_exp_rows.tex (rows of Table 3).
"""
import math
import os
import re
import statistics
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, 'outputs')
FIGS = os.path.join(HERE, 'outputs', 'figs')
os.makedirs(FIGS, exist_ok=True)


def weights(name):
    out = {}
    for line in open(os.path.join(RES, name)):
        m = re.match(r'R=\s*(\d+)\s+B=\s*([\d.]+)', line)
        if m:
            out[int(m.group(1))] = float(m.group(2))
    return out


series = [  # (log, legend, style)  -- distinguishable in grayscale: line pattern and mark
    ('matsui_eelbc_lin_34.log', 'EE-LBC, linear', 'very thick, black, mark=*, mark size=1.1pt'),
    ('matsui_eelbc_diff_34.log', 'EE-LBC, differential', 'thick, black, densely dashed, mark=square*, mark size=1.0pt'),
    ('matsui_present_lin.log', 'PRESENT, linear', 'thick, gray, mark=o, mark size=1.1pt'),
    ('matsui_present_diff.log', 'PRESENT, differential', 'thick, gray, densely dotted, mark=triangle, mark size=1.3pt'),
]
lines = ['% Fig. 2: minimum weights by branch-and-bound.  GENERATED by make_figs.py from outputs/matsui_*.log; do not edit.',
         '\\begin{tikzpicture}',
         '\\begin{axis}[width=0.92\\textwidth, height=5.0cm, font=\\sffamily\\footnotesize,',
         '  xmin=0, xmax=35, ymin=0, ymax=140, xtick={1,5,10,15,20,25,31}, ytick={0,20,40,64,80,100,120,140},',
         '  xlabel={rounds $R$}, ylabel={minimum weight}, grid=major, grid style={gray!25},',
         '  ticklabel style={/pgf/number format/assume math mode=true, font=\\sffamily\\footnotesize},',
         '  legend pos=north west, legend cell align=left, legend style={font=\\sffamily\\scriptsize, draw=none, fill=white, fill opacity=0.9}]']
for name, legend, style in series:
    w = weights(name)
    pts = ' '.join(f'({r},{w[r]:.3f})' for r in sorted(w) if w[r] <= 140)
    lines.append(f'\\addplot[{style}] coordinates {{{pts}}};')
    lines.append(f'\\addlegendentry{{{legend}}}')
lines += ['\\addplot[thin, black, dashed, forget plot] coordinates {(0,64) (35,64)};',
          '\\node[anchor=north west, font=\\sffamily\\scriptsize] at (axis cs:0.5,63) {weight 64 ($2^{-64}$)};',
          '\\addplot[thin, black, dotted, forget plot] coordinates {(31,0) (31,140)};',
          '\\node[anchor=north west, font=\\sffamily\\scriptsize, align=left] at (axis cs:31.3,30) {31\\\\rounds};',
          '\\end{axis}', '\\end{tikzpicture}']
open(os.path.join(FIGS, 'fig_weights.tex'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

# Table 3 rows: L trail rounds; linear over 6 keys (2 keys at L = 13); differential over 4 keys
lin, diff = defaultdict(list), {}
for line in open(os.path.join(RES, 'experiments.log')):
    m = re.match(r'lin\s+r=\s*(\d+).*N=2\^(\d+).*corr=(\S+)', line)
    if m:
        lin[int(m.group(1)) - 1].append((float(m.group(3)), int(m.group(2))))
    m = re.match(r'diff\s+r=\s*(\d+).*N=2\^(\d+).*hits=(\d+)', line)
    if m:
        L = int(m.group(1)) - 1
        h, n = diff.get(L, (0, 0))
        diff[L] = (h + int(m.group(3)), n + 2 ** int(m.group(2)))
rows = ['% Rows of Table 3.  GENERATED by make_figs.py from outputs/experiments.log; do not edit.']
for L in sorted(set(lin) | set(diff)):
    if L in lin:
        v = lin[L]
        lo = min(math.log2(abs(c)) for c, _ in v)
        hi = max(math.log2(abs(c)) for c, _ in v)
        rms = math.log2(sum(c * c for c, _ in v) / len(v)) / 2
        lcell = f'$2^{{{v[0][1]}}}$ & {len(v)} & ${-L}$ & ${lo:.2f}$ to ${hi:.2f}$ & ${rms:.2f}$'
    else:
        lcell = '-- & -- & -- & -- & --'
    if L in diff:
        h, n = diff[L]
        dcell = f'${-3 * L}$ & ${math.log2(h / n):.2f}$'
    else:
        dcell = '-- & --'
    rows.append(f'{L} & {lcell} & {dcell} \\\\')
rows.append('\\bottomrule')  # inside the file: a rule right after \input in a tabular is misplaced
open(os.path.join(FIGS, 'tab_exp_rows.tex'), 'w', encoding='utf-8').write('\n'.join(rows) + '\n')
print('wrote fig_weights.tex and tab_exp_rows.tex')
print('\n'.join(rows))

# Table 5 rows: key recovery on reduced rounds (rank of the correct 20-bit guess)
kr = defaultdict(list)
for fn in ('keyrec_r12_32seeds.log', 'keyrec_longer.log'):
    p = os.path.join(RES, fn)
    if not os.path.exists(p):
        continue
    for line in open(p):
        m = re.search(r'keyrec r=\s*(\d+) trail_layers=\s*(\d+) N=2\^(\d+).*rank of true 20-bit key = (\d+)', line)
        if m:
            r, L, lg, rank = map(int, m.groups())
            kr[(r, L, lg)].append(rank)
krows = ['% Rows of Table 5.  GENERATED by make_figs.py from outputs/keyrec_*.log; do not edit.']
for (r, L, lg) in sorted(kr):
    ranks = kr[(r, L, lg)]
    n = len(ranks)
    krows.append(f'{r} & {L} & $2^{{{lg - 2 * L}}}$ & $2^{{{lg}}}$ & {n} & {sum(x == 1 for x in ranks)} & '
                 f'{sum(x <= 1024 for x in ranks)} & {statistics.median(ranks):g} \\\\')   # usual median: mean of the two middle values
krows.append('\\bottomrule')
if kr:
    open(os.path.join(FIGS, 'tab_keyrec_rows.tex'), 'w', encoding='utf-8').write('\n'.join(krows) + '\n')
    print('\n'.join(krows))
